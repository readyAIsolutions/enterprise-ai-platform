def main():
    import argparse
    parser = argparse.ArgumentParser(description="ENI Skill Forge Swarm")
    parser.add_argument("--workers", type=int, default=4, help="Number of parallel workers")
    parser.add_argument("--spec-dir", type=Path, default=SPEC_DIR, help="Directory with skill specs")
    parser.add_argument("--create-defaults", action="store_true", help="Create default spec files")
    parser.add_argument("--run", action="store_true", help="Run the swarm")
    args = parser.parse_args()

    if args.create_defaults:
        for spec in DEFAULT_SPECS:
            spec_file = args.spec_dir / f"{spec.name}.json"
            spec_file.write_text(json.dumps(asdict(spec), indent=2))
            print(f"Created {spec_file}")
        return

    swarm = SkillForgeSwarm(num_workers=args.workers)
    swarm.load_specs(args.spec_dir)

    if not swarm.specs:
        print("No specs found. Run with --create-defaults to generate examples.")
        return

    if args.run:
        swarm.run()
        print("\n" + swarm.summary())
        # Save summary
        (OUTPUT_DIR / "SWARM_SUMMARY.md").write_text(swarm.summary())
    else:
        print(f"Loaded {len(swarm.specs)} specs. Use --run to execute.")


if __name__ == "__main__":
    main()